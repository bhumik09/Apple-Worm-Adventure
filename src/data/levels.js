export function getLevel(levelId) {
  const index = Math.min(Math.max(levelId, 1), LEVELS.length) - 1;
  return LEVELS[index];
}

export function getWorldForLevel(levelId) {
  const level = getLevel(levelId);
  return WORLDS.find((w) => w.id === level.worldId) || WORLDS[0];
}
